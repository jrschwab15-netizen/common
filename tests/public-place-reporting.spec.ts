import {test,expect} from '@playwright/test';
test('homepage walks through location, Boston trash photo, and optional note',async({page},info)=>{
 await page.goto('/');
 const cards=page.locator('.report-photo-example');await expect(cards).toHaveCount(3);
 const location=page.locator('[data-walkthrough-step="1"]'),photo=page.locator('[data-walkthrough-step="2"]'),note=page.locator('[data-walkthrough-step="3"]');
 await expect(location.locator('.report-example-photo')).toHaveAttribute('src',/boston-location-example\.webp$/);
 await expect(location.locator('.report-example-progress .current')).toHaveText('1. Location');
 await expect(photo.locator('.report-example-photo')).toHaveAttribute('src',/boston-haymarket-trash\.webp$/);
 await expect(photo.locator('.report-example-photo')).toHaveAttribute('alt',/rubbish.*Haymarket.*Boston/);
 await expect(photo.locator('.report-example-progress .current')).toHaveText('2. Photo');
 await expect(note.locator('.report-example-progress .current')).toHaveText('3. Note');
 await expect(page.locator('#impact')).not.toContainText('Chicago');
 const panels=await page.locator('.report-example-ui').evaluateAll(nodes=>nodes.map(node=>({width:node.getBoundingClientRect().width,height:node.getBoundingClientRect().height})));
 expect(Math.max(...panels.map(p=>p.width))-Math.min(...panels.map(p=>p.width))).toBeLessThan(1);
 expect(Math.max(...panels.map(p=>p.height))-Math.min(...panels.map(p=>p.height))).toBeLessThan(1);
 await note.getByRole('textbox',{name:'Example report note'}).fill('An optional example note.');
 await note.getByRole('combobox',{name:'Example issue category'}).selectOption('Sidewalk obstruction');
 await page.locator('.report-photo-grid').screenshot({path:info.outputPath('three-stage-walkthrough.png')});
 await note.getByRole('button',{name:'Start your own report'}).click();
 await expect(page).toHaveURL(/category=Sidewalk/);
 expect(page.url()).not.toContain('optional');
 await page.getByRole('button',{name:'Continue as guest'}).click();
 await page.getByRole('button',{name:'No immediate emergency'}).click();
 await page.getByText('Manual location & place details',{exact:true}).click();
 await expect(page.getByRole('combobox',{name:'Public place type',exact:true})).toHaveValue('Street / sidewalk');
});
